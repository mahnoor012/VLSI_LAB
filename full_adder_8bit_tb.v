`timescale 1ns / 1ps

module full_adder_8bit_tb;

    reg A0, A1, A2, A3, A4, A5, A6, A7;
    reg B0, B1, B2, B3, B4, B5, B6, B7;
    reg Cin;
    wire S0, S1, S2, S3, S4, S5, S6, S7;
    wire Cout;

    full_adder_8bit uut (
        .A0(A0), .A1(A1), .A2(A2), .A3(A3), .A4(A4), .A5(A5), .A6(A6), .A7(A7),
        .B0(B0), .B1(B1), .B2(B2), .B3(B3), .B4(B4), .B5(B5), .B6(B6), .B7(B7),
        .Cin(Cin),
        .S0(S0), .S1(S1), .S2(S2), .S3(S3), .S4(S4), .S5(S5), .S6(S6), .S7(S7),
        .Cout(Cout)
    );

    initial begin

        // Test 1: 00000000 + 00000000 + 0 = 00000000
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b00000000;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00000000;
        Cin = 0; #100;

        // Test 2: 00000001 + 00000001 + 0 = 00000010
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b00000001;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00000001;
        Cin = 0; #100;

        // Test 3: 00000101 + 00000011 + 0 = 00001000
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b00000101;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00000011;
        Cin = 0; #100;

        // Test 4: 00001111 + 00001010 + 0 = 00011001
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b00001111;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00001010;
        Cin = 0; #100;

        // Test 5: 11111111 + 00000000 + 0 = 11111111
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b11111111;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00000000;
        Cin = 0; #100;

        // Test 6: 11111111 + 00000001 + 0 = 00000000, Cout=1
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b11111111;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00000001;
        Cin = 0; #100;

        // Test 7: 11111111 + 11111111 + 0 = 11111110, Cout=1
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b11111111;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b11111111;
        Cin = 0; #100;

        // Test 8: 00001010 + 00010100 + 1 = 00011111
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b00001010;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00010100;
        Cin = 1; #100;

        // Test 9: 11111111 + 11111111 + 1 = 11111111, Cout=1
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b11111111;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b11111111;
        Cin = 1; #100;

        // Test 10: 01010101 + 00101010 + 0 = 01111111
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b01010101;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00101010;
        Cin = 0; #100;

        // Test 11: 00110011 + 00001100 + 1 = 01000000
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b00110011;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00001100;
        Cin = 1; #100;

        // Test 12: 10000000 + 10000000 + 0 = 00000000, Cout=1
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b10000000;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b10000000;
        Cin = 0; #100;

        // Test 13: 01111111 + 00000001 + 0 = 10000000
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b01111111;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00000001;
        Cin = 0; #100;

        // Test 14: 10101010 + 01010101 + 0 = 11111111
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b10101010;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b01010101;
        Cin = 0; #100;

        // Test 15: 00000000 + 00000000 + 1 = 00000001
        {A7,A6,A5,A4,A3,A2,A1,A0} = 8'b00000000;
        {B7,B6,B5,B4,B3,B2,B1,B0} = 8'b00000000;
        Cin = 1; #100;

        $finish;
    end

endmodule